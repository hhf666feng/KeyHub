// Build the offline extension policy from the same published Markdown sources.
import fs from "node:fs/promises";
import path from "node:path";
const repo = path.resolve(import.meta.dirname, "..");
const escape = value => value.replaceAll("&", "&amp;").replaceAll("<", "&lt;").replaceAll(">", "&gt;").replaceAll('"', "&quot;");
function inline(value) {
  return escape(value).replace(/\[([^\]]+)\]\(([^)]+)\)/g, (_, title, href) => {
    const target = href.startsWith("https://") ? href : `https://github.com/omaekumiko2-create/OpenKeylet/blob/main/${href}`;
    return `<a href="${target}" target="_blank" rel="noopener noreferrer">${title}</a>`;
  });
}
function render(markdown) {
  return markdown.trim().split(/\r?\n\r?\n/).map(block => {
    if (block.startsWith("# ")) return `<h1>${inline(block.slice(2))}</h1>`;
    if (block.startsWith("## ")) return `<h2>${inline(block.slice(3))}</h2>`;
    if (block.startsWith("- ")) return `<ul>${block.split(/\r?\n/).map(line => `<li>${inline(line.slice(2))}</li>`).join("")}</ul>`;
    return `<p>${inline(block)}</p>`;
  }).join("\n");
}
const en = render(await fs.readFile(path.join(repo, "PRIVACY.md"), "utf8"));
const zh = render(await fs.readFile(path.join(repo, "PRIVACY.zh-CN.md"), "utf8"));
const html = `<!doctype html>
<!-- Generated by scripts/sync-extension-privacy.mjs from the root privacy policies. -->
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>OpenKeylet Privacy / 隐私政策</title><style>
:root{color-scheme:light dark;font:16px/1.7 system-ui,sans-serif}body{max-width:820px;margin:40px auto;padding:0 24px}h1{font-size:30px}h2{font-size:21px;margin-top:32px}a{color:light-dark(#225a78,#9acbde)}nav{padding:16px 0;border-bottom:1px solid #8886}li{margin:8px 0}section+section{border-top:1px solid #8886;margin-top:64px;padding-top:24px}
</style></head><body><nav><a href="#english">English</a> · <a href="#chinese">简体中文</a></nav>
<section id="english" lang="en">${en}</section><section id="chinese" lang="zh-CN">${zh}</section></body></html>
`;
await fs.writeFile(path.join(repo, "browser-extension/privacy.html"), html);
console.log("Updated browser-extension/privacy.html from the English and Chinese policies.");
